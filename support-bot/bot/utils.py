import random
import re

from bot.config import MENTION_RE, TAG_RE


def extract_tags(text: str) -> list[str]:
    return TAG_RE.findall(text)


def extract_mentions(text: str) -> list[str]:
    return MENTION_RE.findall(text)


def detect_priority(text: str) -> str:
    text_lower = text.lower()
    if re.search(r"критичн|срочн|high|critical", text_lower):
        return "high"
    if re.search(r"важн|medium|normal", text_lower):
        return "medium"
    return "low"


def is_greeting_or_question(text: str) -> bool:
    text_lower = text.lower()
    patterns = [
        r"\bпривет\b", r"\bздравствуй[те]?\b", r"\bсалам\b", r"\bhello\b", r"\bhi\b",
        r"кто ты", r"откуда", r"зачем", r"для чего", r"что ты умеешь", r"расскажи о себе",
    ]
    return any(re.search(p, text_lower) for p in patterns)


def csv_safe(value) -> str:
    """
    Защита от CSV/Excel-инъекций: если значение начинается с =, +, -, @,
    Excel/Google Sheets может интерпретировать его как формулу при открытии
    экспортированного файла. Экранируем ведущим апострофом.
    """
    s = "" if value is None else str(value)
    if s and s[0] in ("=", "+", "-", "@"):
        return "'" + s
    return s


